#include "build.h"


int
main(int argc, char** argv) {
    int result = 1;

    const char* sanitize = NULL;

    const char* program_name = shift(argv, argc);
    const char* config_header_path = "config.h";

    while (argc > 0) {
        const char* opt = shift(argv, argc);
        if (0 == strncmp(opt, "--san=", 6)) {
            const char* arg = opt + 6;
            if (0 == strlen(arg)) {
                nob_log(NOB_ERROR, "Option '--san' requires an argument.");
                goto fail;
            }
            if (0 == strcmp(arg, "on") || 0 == strcmp(arg, "address")) {
                sanitize = "address";
            } else if (0 == strcmp(arg, "off")) {
                sanitize = NULL;
            } else if (0 == strcmp(arg, "thread")) {
                sanitize = "thread";
            } else if (0 == strcmp(arg, "memory")) {
                sanitize = "memory";
            } else {
                nob_log(
                    NOB_ERROR, "Unrecognized argument to option '--san': "
                    "'%s'. Expected 'on', 'off', 'address', "
                    "'thread' or 'memory'.", arg
                );
                goto fail;
            }
        } else if (0 == strcmp(opt, "--san")) {
            const char* arg = nob_shift(argv, argc);
            if (arg == NULL) {
                nob_log(NOB_ERROR, "Option '--san' requires an argument.");
                goto fail;
            }
            if (0 == strcmp(arg, "on") || 0 == strcmp(arg, "address")) {
                sanitize = "address";
            } else if (0 == strcmp(arg, "off")) {
                sanitize = NULL;
            } else if (0 == strcmp(arg, "thread")) {
                sanitize = "thread";
            } else if (0 == strcmp(arg, "memory")) {
                sanitize = "memory";
            } else {
                nob_log(
                    NOB_ERROR, "Unrecognized argument to option '--san': "
                    "'%s'. Expected 'on', 'off', 'address', "
                    "'thread' or 'memory'.", arg
                );
                goto fail;
            }
        } else if (0 == strcmp(opt, "-h") || 0 == strcmp(opt, "--help")) {
            /* handled by the parent build tool. */
        } else if (0 == strcmp(opt, "--clean")) {
            /* handled by the parent build tool. */
        } else {
            nob_log(NOB_ERROR, "Unknown build configuration option '%s'.", opt);
            goto fail;
        }
    }

    String_Builder config_text = {0};

    nob_sb_append_cstr(&config_text, "/* -----------------------------------------------------------------------------\n");
    nob_sb_append_cstr(&config_text, "Part of the GameFU Station Project under the GNU General Public License v2.0.\n");
    nob_sb_append_cstr(&config_text, "See the LICENSE file and LICENSES directory for more information.\n");
    nob_sb_append_cstr(&config_text, "SPDX-License-Identifier: GPL-2.0-only\n");
    nob_sb_append_cstr(&config_text, "--------------------------------------------------------------------------------\n");
    nob_sb_append_cstr(&config_text, "This file was auto-generated by the project build tooling.\n");
    nob_sb_append_cstr(&config_text, "Any changes to this file will be lost upon a build reconfigure.\n");
    nob_sb_append_cstr(&config_text, "See 'nob.c' at the root of this repository or run './nob --help'.\n");
    nob_sb_append_cstr(&config_text, "----------------------------------------------------------------------------- */\n");
    nob_sb_append_cstr(&config_text, "\n");
    nob_sb_append_cstr(&config_text, "#ifndef GAMEFU_NOB_BUILD_CONFIG_H_\n");
    nob_sb_append_cstr(&config_text, "#define GAMEFU_NOB_BUILD_CONFIG_H_\n");
    nob_sb_append_cstr(&config_text, "\n");
    nob_sb_append_cstr(&config_text, "/* Which exclusive sanitizer to enable, or NULL to disable sanitizers. */\n");
    if (sanitize != NULL)
        nob_sb_appendf(&config_text, "#define CONFIG_SANITIZER  \"%s\"\n", sanitize);
    else nob_sb_appendf(&config_text, "#define CONFIG_SANITIZER  NULL\n");
    nob_sb_append_cstr(&config_text, "\n");
    nob_sb_append_cstr(&config_text, "#endif /* GAMEFU_NOB_BUILD_CONFIG_H_ */\n");
    nob_sb_append_null(&config_text);

    bool has_config = file_exists(config_header_path);
    if (has_config) {
        nob_log(INFO, "configuring...");
    } else {
        String_Builder existing_config_text = {0};
        if (!read_entire_file(config_header_path, &existing_config_text)) {
            goto fail;
        }

        if (
            0 == strcmp(
                config_text.items,
                existing_config_text.items
            )
        ) {
            /* already configured. */
            goto success;
        }

        nob_log(INFO, "reconfiguring...");
    }

    if (
        !write_entire_file(
            config_header_path, config_text.items, config_text.count
        )
    ) {
        goto fail;
    }

    nob_log(NOB_INFO, "created file '%s'", config_header_path);

success:;
    result = 0;
fail:;
    return result;
}


